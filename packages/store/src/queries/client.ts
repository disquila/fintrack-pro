import { QueryClient } from '@tanstack/react-query';

// Это "менеджер кеша" — он решает, как долго хранить данные и когда их обновлять
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 1000 * 60 * 5, // 5 минут — данные считаются "свежими"
      // Через 5 минут при следующем запросе данные обновятся в фоне

      gcTime: 1000 * 60 * 10, // 10 минут — храним в кеше даже если не используются
      // Через 10 минут без использования — удаляем из памяти

      retry: 1, // Если запрос упал — попробовать ещё 1 раз

      refetchOnWindowFocus: true, // Обновлять при фокусе окна
    },
  },
});
